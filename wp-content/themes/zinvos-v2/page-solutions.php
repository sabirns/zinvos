<script>
(function() {
  const solutionTabs = document.querySelectorAll('.zs-solution-tab');
  const solutionType = document.getElementById('solutionType');
  const solutionTitle = document.getElementById('solutionTitle');
  const solutionCopy = document.getElementById('solutionCopy');
  const solutionFeatures = document.getElementById('solutionFeatures');
  const solutionFootnote = document.getElementById('solutionFootnote');
  const solutionLink = document.getElementById('solutionLink');
  
  if (!solutionTabs.length || !solutionType) return;
  
  const solutions = {
    academic: {
      type: 'Academic & Scientific',
      title: 'Conference Management Software for Academic & Scientific Events',
      copy: 'Academic conferences often involve workflows that general event software does not handle well — including abstract submissions, peer review and scoring, accreditation-style attendance tracking, and a professional attendee experience.',
      features: ['Abstract Submission & Peer Review', 'Session-Wise Attendance Tracking', 'Accreditation-Style Certification', 'Registration, App & Onsite in One Platform'],
      footnote: 'Built for research congresses, scientific society meetings, engineering symposiums, and academic conferences that need more than a basic ticketing tool.',
      link: 'Explore Academic & Scientific ↗'
    },
    medical: {
      type: 'Medical & CME',
      title: 'Conference Technology for Medical & CME Events',
      copy: 'Medical conferences can require session-wise attendance, accreditation-style reporting, faculty and program information, workshops, and certificate workflows alongside the standard registration and onsite experience.',
      features: ['Session-Wise Attendance', 'Workshop & Session Access Control', 'Faculty & Program Management', 'Certificate Eligibility Workflows'],
      footnote: 'Use registration, attendee communication, mobile app features, onsite operations, and post-event certification in one connected workflow.',
      link: 'Explore Medical & CME ↗'
    },
    corporate: {
      type: 'Corporate Events',
      title: 'Technology for Corporate Summits & Offsites',
      copy: 'Corporate summits and company events need a polished digital experience that reflects the brand. Zinvos brings registration, mobile event experience, attendee communication, and onsite check-in together for internal and external corporate events.',
      features: ['Branded Registration Flow', 'Mobile Event Experience', 'Attendee Communication', 'QR Check-In & Onsite Management'],
      footnote: 'Suitable for leadership summits, company-wide offsites, internal conferences, and branded corporate events.',
      link: 'Explore Corporate Events ↗'
    },
    associations: {
      type: 'Associations & Societies',
      title: 'Event Technology for Associations & Societies',
      copy: 'Recurring member conferences and annual meetings should not require rebuilding the event technology setup every year. Zinvos provides a reusable foundation for registration, member communication, event management, and attendee experience.',
      features: ['Reusable Event Setup', 'Member Communication', 'Annual Meeting Management', 'Connected Registration & Onsite Operations'],
      footnote: 'Designed for associations and professional societies running recurring conferences and member events.',
      link: 'Explore Associations & Societies ↗'
    }
  };
  
  function renderSolution(key) {
    const item = solutions[key];
    if (!item) return;
    solutionTabs.forEach(tab => tab.classList.toggle('is-active', tab.dataset.solution === key));
    solutionType.textContent = item.type;
    solutionTitle.textContent = item.title;
    solutionCopy.textContent = item.copy;
    solutionFootnote.textContent = item.footnote;
    if (solutionLink) solutionLink.textContent = item.link;
    solutionFeatures.innerHTML = item.features.map((feature, index) => 
      `<div class="zs-detail__feature"><small>${String(index + 1).padStart(2, '0')}</small><strong>${feature}</strong></div>`
    ).join('');
  }

  function handleHash() {
    const hash = window.location.hash.replace('#', '');
    if (hash && solutions[hash]) {
      renderSolution(hash);
      const sec = document.getElementById('solutions');
      if (sec) {
        const header = document.querySelector('.top-wrap, .site-header');
        const headerOffset = header ? header.offsetHeight + 20 : 100;
        const pos = Math.max(0, sec.getBoundingClientRect().top + window.pageYOffset - headerOffset);
        window.scrollTo({ top: pos, behavior: 'smooth' });
      }
    }
  }

  solutionTabs.forEach(tab => {
    tab.addEventListener('click', () => renderSolution(tab.dataset.solution));
  });

  handleHash();
  window.addEventListener('hashchange', handleHash);
})();
</script>

